// Command gen generates stubs_gen_arm64.go and stubs_gen_amd64.go, one
// distinct trampoline function per dispatch slot.
//
// Run it with:
//
//	go generate ./...
//
// Each generated function has the architecture's maximal register signature
// plus a single trailing stack argument. The trailing argument exists so that
// its address is the base of the caller's stack argument area, which the
// dispatcher uses to read stack-assigned arguments and write stack-assigned
// results (see dispatch). Every slot is a separate function, so the compiler
// emits a distinct code pointer per slot, which is exactly what itab.Fun[k]
// needs: a bare code pointer with no closure context.
package main

import (
	"fmt"
	"os"
	"strings"
)

const slots = 128

func main() {
	gen("arm64", "arm64", 16, 16)
	gen("amd64", "amd64", 9, 15)
}

func gen(filename, tag string, ni, nf int) {
	var b strings.Builder
	b.WriteString("// Code generated by gen/main.go; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "//go:build %s\n\n", tag)
	b.WriteString("package weave\n\n")
	b.WriteString("import \"unsafe\"\n\n")
	fmt.Fprintf(&b, "const slotCount = %d\n\n", slots)

	for k := 0; k < slots; k++ {
		// The two directives below are both load-bearing, for two distinct
		// register-parameter home-slot problems. A register parameter's ABI
		// home lives in the CALLER's outgoing argument area, and a direct
		// call to the stub's signature would reserve all 32 of them. An itab
		// call site, however, is compiled against the method's signature and
		// reserves only the method's own homes.
		//
		//   - //go:norace: the race prologue spills all parameters across the
		//     racefuncenter call, straight into the unreserved homes.
		//
		//   - //go:nosplit: a split function's morestack trampoline saves all
		//     argument registers to their homes before growing the stack
		//     (they are not part of gobuf), again writing ~250 bytes past the
		//     itab caller's reservation. nosplit removes the stack check, and
		//     the ~300 byte frame is well under the StackNosplit limit.
		//
		// The stub is a pure register conduit with no memory accesses, so
		// excluding it from race instrumentation loses nothing: everything
		// from dispatch down stays fully instrumented.
		b.WriteString("//go:nosplit\n//go:norace\n")
		fmt.Fprintf(&b, "func stub%d(%s) (%s) {\n", k, params(ni, nf), results(ni, nf))
		fmt.Fprintf(&b, "\treturn dispatch(%d, %s, %s)\n", k, seq(ni, "a"), seq(nf, "f"))
		b.WriteString("}\n\n")
	}

	b.WriteString("var stubs = [...]fastFunc{\n")
	for k := 0; k < slots; k++ {
		fmt.Fprintf(&b, "\tstub%d,\n", k)
	}
	b.WriteString("}\n")

	if err := os.WriteFile("stubs_gen_"+filename+".go", []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
}

func seq(n int, prefix string) string {
	var p []string
	for i := 0; i < n; i++ {
		p = append(p, fmt.Sprintf("%s%d", prefix, i))
	}
	return strings.Join(p, ", ")
}

// params returns "a0..aN uintptr, f0..fM float64". The integer registers are
// typed uintptr so that the stub's spill of the (possibly garbage) registers
// into its frame is never scanned as pointers; the dispatcher copies the
// registers that actually hold pointers into GC-visible storage.
func params(ni, nf int) string {
	return seq(ni, "a") + " uintptr, " + seq(nf, "f") + " float64"
}

func results(ni, nf int) string {
	return seq(ni, "r") + " unsafe.Pointer, " + seq(nf, "g") + " float64"
}
